#ARITHMETIC OPERATORS>>
#Basic > +,-,*,/
x = 10//3 # Floor Division (Answer as a integer only)
x = 10%3 # Remainder
x = 10**3 # Exponential

#ASSIGNMENT OPERATORS>>
x+=5            # Increament
x-=5            # Decreament
x *= 2          # x = x * 2  → 24
x /= 4          # x = x / 4  → 6.0
x //= 2         # x = x // 2 → 3.0
x %= 2          # x = x % 2  → 1.0
x **= 3         # x = x ** 3 → 1.0

#LOGICAL OPERATORS
x, y = True, False

print(x and y)   # False (both must be True)
print(x or y)    # True  (at least one True)
print(not x)     # False

#MEMBERSHIP OPERATOR
nums = [1, 2, 3, 4]
print(2 in nums)       # True
print(5 not in nums)   # True

